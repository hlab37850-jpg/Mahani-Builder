function collectDartContext(projectName, maxFiles = 40, maxCharsPerFile = 14000, maxTotalChars = 90000) {
  const projectRoot = root(projectName);
  const files = collectFiles(projectName);
  const result = [];
  let total = 0;

  for (const relative of files.slice(0, maxFiles)) {
    const full = path.join(projectRoot, relative);

    if (!fs.existsSync(full)) {
      continue;
    }

    let content = fs.readFileSync(full, 'utf8');

    if (content.length > maxCharsPerFile) {
      content =
        content.slice(0, maxCharsPerFile) +
        '\n\n// [CONTEXT TRUNCATED]\n';
    }

    if (total + content.length > maxTotalChars) {
      break;
    }

    result.push({
      path: relative,
      content
    });

    total += content.length;
  }

  return result;
}

