function ensureFlutterPubspecDependencies(projectName, plan) {
  const projectRoot = root(projectName);

  const pubspecPath = path.join(
    projectRoot,
    'pubspec.yaml'
  );

  if (!fs.existsSync(pubspecPath)) {
    throw new Error(
      'PUBSPEC_NOT_FOUND: Flutter project did not create pubspec.yaml'
    );
  }

  let content = fs.readFileSync(
    pubspecPath,
    'utf8'
  );

  const dependencies = {
    flutter_localizations: null,
    ...PACKAGE_VERSIONS
  };

  const lines = content.split(/\r?\n/);

  let dependenciesIndex = lines.findIndex(
    line => line.trim() === 'dependencies:'
  );

  if (dependenciesIndex === -1) {
    throw new Error(
      'PUBSPEC_INVALID: dependencies section not found'
    );
  }

  let dependenciesEnd = lines.findIndex(
    (line, index) =>
      index > dependenciesIndex &&
      line.length > 0 &&
      !line.startsWith(' ') &&
      !line.startsWith('#')
  );

  if (dependenciesEnd === -1) {
    dependenciesEnd = lines.length;
  }

  const existing = new Set();

  for (
    let i = dependenciesIndex + 1;
    i < dependenciesEnd;
    i++
  ) {
    const match = lines[i].match(
      /^  ([a-zA-Z0-9_]+):/
    );

    if (match) {
      existing.add(match[1]);
    }
  }

  const additions = [];

  if (!existing.has('flutter_localizations')) {
    additions.push(
      '  flutter_localizations:',
      '    sdk: flutter'
    );
  }

  for (const [name, version] of Object.entries(
    PACKAGE_VERSIONS
  )) {
    if (existing.has(name)) {
      continue;
    }

    additions.push(
      '  ' + name + ': ' + version
    );
  }

  if (additions.length > 0) {
    lines.splice(
      dependenciesEnd,
      0,
      ...additions
    );
  }

  content = lines.join('\n');

  fs.writeFileSync(
    pubspecPath,
    content,
    'utf8'
  );

  console.log(
    '[ENGINE] Flutter pubspec dependencies configured'
  );

  return pubspecPath;
}


