function safeProjectName(name) {
  return String(name || 'mahani_app')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9_]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .replace(/_+/g, '_')
    .slice(0, 50) || `mahani_app_${Date.now()}`;
}

function root(projectName) {
  return path.join(
    __dirname,
    'projects',
    safeProjectName(projectName)
  );
}


function createFlutterAndroidProject(projectName, plan) {
  const projectRoot = root(projectName);
  const projectNameSafe = safeProjectName(projectName);

  fs.mkdirSync(
    path.dirname(projectRoot),
    { recursive: true }
  );

  console.log(
    '[ENGINE] إنشاء Flutter Android project حقيقي'
  );

  if (
    fs.existsSync(projectRoot) &&
    fs.existsSync(path.join(projectRoot, 'android'))
  ) {
    console.log(
      '[ENGINE] Android project موجود بالفعل'
    );
    return projectRoot;
  }

  if (fs.existsSync(projectRoot)) {
    fs.rmSync(
      projectRoot,
      {
        recursive: true,
        force: true
      }
    );
  }

  execFileSync(
    'flutter',
    [
      'create',
      '--platforms=android',
      '--project-name',
      projectNameSafe,
      projectRoot
    ],
    {
      stdio: 'inherit',
      timeout: 180000
    }
  );

  // Normalize Dart SDK constraint so the generated project
  // remains compatible with the Flutter version used by GitHub Actions.
  const generatedPubspec = path.join(
    projectRoot,
    'pubspec.yaml'
  );

  if (fs.existsSync(generatedPubspec)) {
    let pubspecContent = fs.readFileSync(
      generatedPubspec,
      'utf8'
    );

    pubspecContent = pubspecContent.replace(
      /^\s*sdk:\s*\^3\.\d+\.\d+\s*$/m,
      "    sdk: '>=3.9.0 <4.0.0'"
    );

    fs.writeFileSync(
      generatedPubspec,
      pubspecContent,
      'utf8'
    );

    console.log(
      '[ENGINE] Dart SDK constraint normalized to >=3.9.0 <4.0.0'
    );
  }

  if (
    !fs.existsSync(
      path.join(projectRoot, 'android')
    )
  ) {
    throw new Error(
      'FLUTTER_CREATE_FAILED: مجلد android لم يتم إنشاؤه'
    );
  }

  // Normalize Kotlin Android Gradle configuration generated by Flutter.
  // Prevents `kotlin { compilerOptions { jvmTarget = ... } }`
  // from failing when the Kotlin Android plugin is missing.
  const androidAppGradle = path.join(
    projectRoot,
    'android',
    'app',
    'build.gradle.kts'
  );

  if (fs.existsSync(androidAppGradle)) {
    let gradleContent = fs.readFileSync(
      androidAppGradle,
      'utf8'
    );

    const kotlinPlugin = '    id("org.jetbrains.kotlin.android")';

    if (
      !gradleContent.includes(
        'id("org.jetbrains.kotlin.android")'
      )
    ) {
      const androidPlugin = '    id("com.android.application")';

      if (!gradleContent.includes(androidPlugin)) {
        throw new Error(
          'FLUTTER_ANDROID_GRADLE_PATCH_FAILED: com.android.application plugin not found'
        );
      }

      gradleContent = gradleContent.replace(
        androidPlugin,
        androidPlugin + '\\n' + kotlinPlugin,
        1
      );

      fs.writeFileSync(
        androidAppGradle,
        gradleContent,
        'utf8'
      );

      console.log(
        '[ENGINE] Kotlin Android plugin added automatically'
      );
    } else {
      console.log(
        '[ENGINE] Kotlin Android plugin already present'
      );
    }
  } else {
    throw new Error(
      'FLUTTER_ANDROID_GRADLE_PATCH_FAILED: android/app/build.gradle.kts not found'
    );
  }


  if (
    !fs.existsSync(
      path.join(projectRoot, 'pubspec.yaml')
    )
  ) {
    throw new Error(
      'FLUTTER_CREATE_FAILED: pubspec.yaml لم يتم إنشاؤه'
    );
  }

  console.log(
    '[ENGINE] تم إنشاء Flutter Android project بنجاح'
  );

  return projectRoot;
}

async function askAI(apiKey, messages, maxTokens = 5000) {
  const { execFile } = require('child_process');

  const models = [
    'nvidia/nemotron-3-super-120b-a12b:free',
    ...(process.env.GROQ_API_KEY ? ['groq/openai/gpt-oss-20b'] : []),
    'openai/gpt-oss-20b:free',
    'cohere/north-mini-code:free'
  ].filter((value, index, array) =>
    value && array.indexOf(value) === index
  );

  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));

  function extractJson(text) {
    let clean = String(text || '')
      .replace(/^```json\s*/i, '')
      .replace(/^```\s*/i, '')
      .replace(/\s*```$/i, '')
      .trim();

    try {
      return JSON.parse(clean);
    } catch (_) {}

    const first = clean.indexOf('{');
    const last = clean.lastIndexOf('}');

    if (first >= 0 && last > first) {
      const candidate = clean.slice(first, last + 1);
      try {
        return JSON.parse(candidate);
      } catch (_) {}
    }

    throw new Error(
      'AI returned invalid/incomplete JSON: ' +
      clean.slice(0, 3000)
    );
  }

  function callCurl(model, tokenLimit) {
    const isGroq = model.startsWith('groq/');
    const provider = isGroq ? 'Groq' : 'OpenRouter';

    const actualModel = isGroq
      ? model.slice(5)
      : model;

    const endpoint = isGroq
      ? 'https://api.groq.com/openai/v1/chat/completions'
      : 'https://openrouter.ai/api/v1/chat/completions';

    const providerKey = isGroq
      ? process.env.GROQ_API_KEY
      : apiKey;

    if (!providerKey) {
      throw new Error(provider + ' API key is missing');
    }

    const payloadObject = {
      model: actualModel,
      messages,
      temperature: 0,
      response_format: { type: 'json_object' }
    };

    if (isGroq) {
      payloadObject.max_completion_tokens = tokenLimit;
    } else {
      payloadObject.max_tokens = tokenLimit;
    }

    const payload = JSON.stringify(payloadObject);

    console.log(
      '[AI] provider=' + provider +
      ' model=' + actualModel +
      ' tokens=' + tokenLimit
    );

    return new Promise((resolve, reject) => {
      execFile(
        'curl',
        [
          '--silent',
          '--show-error',
          '--fail-with-body',
          '--connect-timeout', '30',
          '--max-time', '120',
          endpoint,
          '-H', 'Authorization: Bearer ' + providerKey,
          '-H', 'Content-Type: application/json',

          ...(isGroq
            ? []
            : [
                '-H', 'HTTP-Referer: http://127.0.0.1:3000',
                '-H', 'X-Title: Mahani Builder AI'
              ]),

          '--data', payload
        ],
        {
          maxBuffer: 30 * 1024 * 1024
        },
        (error, stdout, stderr) => {
          const raw = String(stdout || '').trim();
          const err = String(stderr || '').trim();

          let data = null;

          if (raw) {
            try {
              data = JSON.parse(raw);
            } catch (_) {}
          }

          if (error) {
            const providerError =
              data && data.error
                ? JSON.stringify(data.error)
                : raw.slice(0, 5000);

            reject(new Error(
              provider + ' curl failed: ' +
              (err || error.message) +
              '; RESPONSE=' +
              providerError
            ));
            return;
          }

          if (!data) {
            reject(new Error(
              provider + ' returned empty JSON'
            ));
            return;
          }

          if (data.error) {
            reject(new Error(
              provider + ' API error: ' +
              JSON.stringify(data.error).slice(0, 5000)
            ));
            return;
          }

          const choice = data.choices?.[0];
          const finish =
            choice?.finish_reason || 'unknown';

          const content =
            choice?.message?.content;

          console.log(
            '[AI] model=' +
            (data.model || actualModel) +
            ' provider=' +
            (data.provider || provider) +
            ' tokens=' +
            tokenLimit +
            ' finish=' +
            finish +
            ' content=' +
            (typeof content === 'string'
              ? content.length
              : 0)
          );

          if (!content) {
            reject(new Error(
              'AI returned no content: finish_reason=' +
              finish +
              '; usage=' +
              JSON.stringify(
                data.usage || {}
              ).slice(0, 3000)
            ));
            return;
          }

          try {
            resolve(extractJson(content));
          } catch (jsonError) {
            reject(new Error(
              jsonError.message +
              '; finish_reason=' +
              finish
            ));
          }
        }
      );
    });
  }

  const firstLimit = Math.min(
    Math.max(2500, Number(maxTokens) || 6000),
    9000
  );

  let lastError = null;

  for (const model of models) {
    console.log('');
    console.log('[AI] محاولة النموذج: ' + model);

    try {
      console.log('[AI] tokens=' + firstLimit);
      return await callCurl(model, firstLimit);

    } catch (firstError) {
      lastError = firstError;

      const msg = String(firstError.message || '');

      console.log(
        '[AI] فشل النموذج ' + model + ':'
      );
      console.log(msg);

      // 401: توقف فوريًا لأن المفتاح نفسه غير صالح.
      if (/401|invalid.*api.*key|authentication/i.test(msg)) {
        throw new Error(
          'OPENROUTER_AUTH_FAILED: ' + msg
        );
      }

      // 429: لا تعيد المحاولة بنفس النموذج.
      // وإذا كان الحد اليومي عامًا، لا تحرق بقية الطلبات.
      if (
        /429|free-models-per-day|rate.?limit|too many requests/i.test(msg)
      ) {
        console.log(
          '[AI] 429 — تم إيقاف إعادة المحاولة لهذا النموذج'
        );

        if (/free-models-per-day/i.test(msg)) {
          lastError = new Error(
            'OPENROUTER_FREE_DAILY_LIMIT_REACHED'
          );
          continue;
        }

        await sleep(1500);
        continue;
      }

      // 402 / credits / quota
      if (/402|payment|insufficient|credits|quota/i.test(msg)) {
        console.log(
          '[AI] الرصيد/الحصة غير متاحة — النموذج التالي'
        );
        continue;
      }

      // Timeout / 5xx:
      // تجربة واحدة فقط بحجم أصغر.
      if (
        /500|502|503|504|timeout|timed out|curl failed/i.test(msg)
      ) {
        console.log(
          '[AI] خطأ مؤقت — محاولة أصغر مرة واحدة'
        );

        try {
          return await callCurl(
            model,
            Math.max(3000, Math.floor(firstLimit * 0.55))
          );
        } catch (secondError) {
          lastError = secondError;
          console.log(
            '[AI] فشلت المحاولة المختصرة — النموذج التالي'
          );
          continue;
        }
      }

      // JSON غير صالح أو إخراج مبتور:
      // لا نكرر 8000 token؛ ننتقل للنموذج التالي.
      if (
        /invalid.*json|incomplete.*json|finish_reason=length/i.test(msg)
      ) {
        console.log(
          '[AI] JSON غير صالح/مبتور — النموذج التالي'
        );
        continue;
      }

      continue;
    }
  }

  if (
    lastError &&
    lastError.message === 'OPENROUTER_FREE_DAILY_LIMIT_REACHED'
  ) {
    throw new Error(
      'OPENROUTER_FREE_DAILY_LIMIT_REACHED: ' +
      'تم استنفاد حد OpenRouter المجاني اليومي. ' +
      'لن يتم حرق طلبات إضافية بإعادة المحاولة.'
    );
  }

  throw new Error(
    'AI generation failed: all fallback models failed. LAST=' +
    (lastError ? lastError.message : 'unknown error')
  );
}

