async function buildProject(
  apiKey,
  projectName,
  plan
) {
  if (!apiKey) {
    throw new Error(
      'OPENROUTER_API_KEY غير موجود'
    );
  }

  const projectRoot =
    createFlutterAndroidProject(
      projectName,
      plan
    );

  ensureFlutterPubspecDependencies(
    projectName,
    plan
  );

  console.log(
    '[ENGINE] Flutter Android project + dependencies configured'
  );

  // ============================================================
  // MAHANI 16-STAGE PIPELINE
  // Each major stage is split into 4 small dependent stages.
  // Later stages receive the files generated by earlier stages.
  // ============================================================

  const stages = [
    'core-1-foundation',
    'core-2-config',
    'core-3-routing',
    'core-4-bootstrap',

    'data-1-models',
    'data-2-schema',
    'data-3-repositories',
    'data-4-integration',

    'services-1-storage',
    'services-2-feature-services',
    'services-3-business-logic',
    'services-4-integration',

    'ui-1-shell',
    'ui-2-primary-features',
    'ui-3-secondary-features',
    'ui-4-integration'
  ];

    // ============================================================
    // MAHANI CHECKPOINT / RESUME
    // ============================================================

    const checkpointPath = path.join(
      projectRoot,
      '.mahani-checkpoint.json'
    );

    let checkpoint = {
      version: 2,
      projectName,
      appName: plan?.appName || '',
      description: plan?.description || '',
      appType: plan?.appType || '',
      design: plan?.design || '',
      completedStages: [],
      results: []
    };

    if (fs.existsSync(checkpointPath)) {
      try {
        const saved = JSON.parse(
          fs.readFileSync(checkpointPath, 'utf8')
        );

        if (
          saved &&
          (saved.version === 1 || saved.version === 2) &&
          saved.projectName === projectName &&
          Array.isArray(saved.completedStages)
        ) {
          checkpoint = saved;

          console.log(
            '[CHECKPOINT] تم استعادة حالة البناء السابقة'
          );

          console.log(
            '[CHECKPOINT] المراحل المكتملة: ' +
            checkpoint.completedStages.join(', ')
          );
        }
      } catch (error) {
        console.log(
          '[CHECKPOINT] الحالة السابقة غير صالحة — بدء جديد'
        );
      }
    }

    const results = Array.isArray(checkpoint.results)
      ? checkpoint.results
      : [];

    let existingFiles = collectDartContext(projectName);

    for (const stage of stages) {
      if (checkpoint.completedStages.includes(stage)) {
        console.log(
          `[CHECKPOINT] تخطي ${stage} — محفوظ سابقًا، والتحقق النهائي مؤجل إلى GitHub Actions`
        );

        existingFiles = collectDartContext(projectName);
        continue;
      }

      console.log(
        `[ENGINE] بدء المرحلة الآمنة: ${stage}`
      );

      try {
        const stageResult =
          await runStageSafely(
            apiKey,
            projectName,
            plan,
            stage,
            existingFiles,
            3
          );

        existingFiles =
          stageResult.files;

        results.push({
          stage,
          generated: stageResult.generated,
          written: stageResult.written,
          repaired: stageResult.repaired,
          repairAttempts:
            stageResult.repairAttempts || 0,
          files: existingFiles.length,
          completedAt:
            new Date().toISOString()
        });

        checkpoint.completedStages.push(stage);
        checkpoint.results = results;

        fs.writeFileSync(
          checkpointPath,
          JSON.stringify(checkpoint, null, 2),
          'utf8'
        );

        console.log(
          `[CHECKPOINT] تم حفظ ${stage} بعد نجاح analyze`
        );

      } catch (error) {
        checkpoint.results = results;

        fs.writeFileSync(
          checkpointPath,
          JSON.stringify(checkpoint, null, 2),
          'utf8'
        );

        console.log(
          `[CHECKPOINT] توقف البناء عند ${stage}`
        );

        console.log(
          `[CHECKPOINT] السبب: ${error.message}`
        );

        throw error;
      }
    }

    if (
      checkpoint.completedStages.length === stages.length
    ) {
      try {
        fs.unlinkSync(checkpointPath);

        console.log(
          '[CHECKPOINT] اكتملت جميع مراحل AI — تم حذف checkpoint'
        );
      } catch (error) {
        console.log(
          '[CHECKPOINT] تعذر حذف checkpoint: ' +
          error.message
        );
      }
    }

console.log(
    '[ENGINE] التحقق من ملفات المشروع قبل GitHub Actions'
  );

  let validation =
    validateGeneratedFiles(
      projectName
    );

  if (!validation.valid) {
    throw new Error(
      `PROJECT_VALIDATION_FAILED: ${validation.errors.join('; ')}`
    );
  }

    // GitHub-only build pipeline.
  // Flutter pub get, analyze, repair and APK build run on GitHub Actions only.
  console.log(
    '[ENGINE] GitHub-only pipeline: local Flutter execution skipped'
  );

  writeGitHubWorkflow(projectName);

  const githubActions = require('./github-actions');

  const githubOwner = String(
    process.env.GITHUB_OWNER || ''
  ).trim();

  const githubToken = String(
    process.env.GITHUB_TOKEN || ''
  ).trim();

  if (!githubOwner) {
    throw new Error(
      'GITHUB_BUILD_FAILED: GITHUB_OWNER غير موجود في .env'
    );
  }

  if (!githubToken) {
    throw new Error(
      'GITHUB_BUILD_FAILED: GITHUB_TOKEN غير موجود في .env'
    );
  }

  const githubOutputDir = path.join(
    projectRoot,
    'github-build'
  );

  fs.mkdirSync(githubOutputDir, {
    recursive: true
  });

  console.log(
    '[ENGINE] بدء البناء الحقيقي عبر GitHub Actions'
  );

  const githubBuild =
    await githubActions.buildProject(
      githubOwner,
      projectName,
      githubToken,
      projectRoot,
      githubOutputDir
    );

  const apkPath = githubBuild.apkPath;

  console.log(
    '[ENGINE] تم إنشاء APK عبر GitHub Actions: ' +
    apkPath
  );

  return {
    projectRoot,
    apkPath,
    github: githubBuild,
    files: collectAllProjectFiles(
      projectName
    ),
    dartFiles: collectFiles(
      projectName
    ),
    importedPackages:
      validation.importedPackages,
    stages: results,
    validation
  };
}

