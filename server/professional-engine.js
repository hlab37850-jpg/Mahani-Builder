function validateDartConsistency(projectName) {
  const projectRoot = root(projectName);
  const libRoot = path.join(projectRoot, 'lib');
  const errors = [];

  if (!fs.existsSync(libRoot)) {
    return { valid: false, errors: ['lib directory غير موجود'] };
  }

  const dartFiles = [];

  function walk(dir) {
    for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, item.name);

      if (item.isDirectory()) {
        walk(full);
      } else if (item.isFile() && item.name.endsWith('.dart')) {
        dartFiles.push(full);
      }
    }
  }

  walk(libRoot);

  const relativeDartFiles = new Set(
    dartFiles.map(full =>
      path.relative(libRoot, full).split(path.sep).join('/')
    )
  );

  let packageName = safeProjectName(projectName);

  const pubspecPath = path.join(projectRoot, 'pubspec.yaml');

  if (fs.existsSync(pubspecPath)) {
    const pubspec = fs.readFileSync(pubspecPath, 'utf8');
    const match = pubspec.match(/^name:\s*([A-Za-z0-9_]+)\s*$/m);

    if (match) {
      packageName = match[1];
    }
  }

  const declarations = new Map();
  const allSource = new Map();

  for (const full of dartFiles) {
    const relative = path.relative(libRoot, full)
      .split(path.sep)
      .join('/');

    const source = fs.readFileSync(full, 'utf8');

    allSource.set(relative, source);

    const names = [
      ...source.matchAll(
        /\b(?:class|enum|mixin|extension)\s+([A-Za-z_]\w*)/g
      )
    ].map(m => m[1]);

    for (const name of names) {
      if (!declarations.has(name)) {
        declarations.set(name, []);
      }

      declarations.get(name).push(relative);
    }
  }

  for (const [relative, source] of allSource) {
    const imports = [
      ...source.matchAll(/import\s+['"]([^'"]+)['"]/g)
    ].map(m => m[1]);

    for (const importPath of imports) {

      if (importPath.startsWith('package:')) {
        const match = importPath.match(/^package:([^/]+)\/(.+)$/);

        if (!match) {
          errors.push(
            relative + ': package import غير صالح: ' + importPath
          );
          continue;
        }

        const importedPackage = match[1];
        const importedFile = match[2];

        if (importedPackage === packageName) {
          if (!relativeDartFiles.has(importedFile)) {
            errors.push(
              relative +
              ': import داخلي غير موجود: ' +
              importPath
            );
          }
        } else if (!PACKAGE_VERSIONS[importedPackage]) {
          errors.push(
            relative +
            ': package غير موجود في PACKAGE_VERSIONS: ' +
            importedPackage
          );
        }
      }

      if (
        importPath.startsWith('../') ||
        importPath.startsWith('./')
      ) {
        const currentDir = path.posix.dirname(relative);

        const normalized = path.posix.normalize(
          path.posix.join(currentDir, importPath)
        );

        if (!relativeDartFiles.has(normalized)) {
          errors.push(
            relative +
            ': relative import غير موجود: ' +
            importPath
          );
        }
      }
    }
  }

  // Generic project consistency validation.
  // يتم الاعتماد على:
  // 1. صحة مسارات Dart الداخلية.
  // 2. وجود الملفات المستوردة.
  // 3. وجود الحزم المعروفة.
  // 4. وجود lib/main.dart.
  // 5. سلامة اسم package في pubspec.
  const uniqueErrors = [...new Set(errors)];

  return {
    valid: uniqueErrors.length === 0,
    errors: uniqueErrors,
    dartFiles: relativeDartFiles.size,
    packageName
  };
}


