function normalizeLocalPackageImports(projectName, source) {
  const projectPackage = safeProjectName(projectName);

  return String(source || '').replace(
    /package:([a-zA-Z0-9_]+)\//g,
    (full, packageName) => {
      // Keep the current project's own package imports unchanged.
      if (packageName === projectPackage) {
        return full;
      }

      // Keep every known external Flutter/Dart package unchanged.
      if (PACKAGE_VERSIONS[packageName]) {
        return full;
      }

      // Flutter SDK packages must ALWAYS remain external imports.
      if (
        packageName === 'flutter' ||
        packageName === 'flutter_localizations' ||
        packageName === 'cupertino'
      ) {
        return full;
      }

      // Unknown package imports are left untouched.
      // The validator will report them if the dependency is missing.
      return full;
    }
  );
}

function writeFiles(projectName, files) {
  const projectRoot = root(projectName);
  const libRoot = path.join(
    projectRoot,
    'lib'
  );

  fs.mkdirSync(
    libRoot,
    { recursive: true }
  );

  let written = 0;

  for (
    const file of Array.isArray(files)
      ? files
      : []
  ) {
    if (
      !file ||
      typeof file !== 'object'
    ) {
      continue;
    }

    const relative = String(
      file.path || ''
    ).trim();

    if (
      !relative.startsWith('lib/') ||
      relative.includes('..') ||
      relative.includes('\\') ||
      !relative.endsWith('.dart')
    ) {
      continue;
    }

    const full = path.resolve(
      projectRoot,
      relative
    );

    if (
      !full.startsWith(
        path.resolve(libRoot) +
        path.sep
      )
    ) {
      continue;
    }

    const content = normalizeLocalPackageImports(
      projectName,
      String(file.content || '').trim()
    );

    if (!content) continue;

    fs.mkdirSync(
      path.dirname(full),
      { recursive: true }
    );

    fs.writeFileSync(
      full,
      content + '\n',
      'utf8'
    );

    written++;
  }

  return written;
}

function collectFiles(projectName) {
  const projectRoot = root(projectName);
  const result = [];

  if (!fs.existsSync(projectRoot)) {
    return result;
  }

  function walk(dir) {
    for (
      const item of fs.readdirSync(
        dir,
        { withFileTypes: true }
      )
    ) {
      const full = path.join(
        dir,
        item.name
      );

      if (item.isDirectory()) {
        walk(full);
      } else if (
        item.isFile() &&
        item.name.endsWith('.dart')
      ) {
        result.push(
          path.relative(
            projectRoot,
            full
          )
        );
      }
    }
  }

  walk(
    path.join(
      projectRoot,
      'lib'
    )
  );

  return result.sort();
}

function collectAllProjectFiles(projectName) {
  const projectRoot = root(projectName);

  if (!fs.existsSync(projectRoot)) {
    return [];
  }

  const result = [];

  function walk(dir) {
    for (
      const item of fs.readdirSync(
        dir,
        { withFileTypes: true }
      )
    ) {
      const full = path.join(
        dir,
        item.name
      );

      if (item.isDirectory()) {
        walk(full);
      } else {
        result.push(
          path.relative(
            projectRoot,
            full
          )
        );
      }
    }
  }

  walk(projectRoot);

  return result.sort();
}

function detectImportedPackages(
  projectName
) {
  const projectRoot = root(projectName);
  const packages = new Set();

  for (
    const relative of collectFiles(projectName)
  ) {
    const full = path.join(
      projectRoot,
      relative
    );

    const source = fs.readFileSync(
      full,
      'utf8'
    );

    const regex =
      /import\s+['"]package:([^/]+)\//g;

    let match;

    while (
      (match = regex.exec(source))
    ) {
      const packageName = match[1];

      if (
        PACKAGE_VERSIONS[packageName]
      ) {
        packages.add(packageName);
      }
    }
  }

  return [...packages].sort();
}

function validateGeneratedFiles(
  projectName
) {
  const projectRoot = root(projectName);

  const errors = [];

  const files =
    collectFiles(projectName);

  if (!files.includes('lib/main.dart')) {
    errors.push(
      'lib/main.dart غير موجود'
    );
  }

  const pubspecPath = path.join(
    projectRoot,
    'pubspec.yaml'
  );

  if (!fs.existsSync(pubspecPath)) {
    errors.push(
      'pubspec.yaml غير موجود'
    );
  }

  const importedPackages =
    detectImportedPackages(projectName);

  for (
    const packageName of importedPackages
  ) {
    if (
      !PACKAGE_VERSIONS[packageName]
    ) {
      errors.push(
        `Package غير معروف: ${packageName}`
      );
    }
  }

  return {
    valid: errors.length === 0,
    errors,
    files,
    importedPackages
  };
}


